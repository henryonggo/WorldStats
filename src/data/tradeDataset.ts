interface RawCountryTradeSpec {
  code: string;
  // 2025 Global Harmonized baseline (USD Billions)
  gExp25: number;
  gImp25: number;
  sExp25: number;
  sImp25: number;
  // Multi-year trajectory multipliers relative to 2025 baseline
  yoy24: number; // 2024->2025 growth %
  yoy26: number; // 2025->2026 growth %
  // Latest available year in each reference source (demonstrates realistic publication lags)
  globalLatestYear: TradeYear;
  nationalLatestYear: TradeYear;
  // National customs variance ratios vs. Global Harmonized (FOB/CIF, re-exports, FX windows)
  natExpRatio: number;
  natImpRatio: number;
  natSvcExpRatio: number;
  natSvcImpRatio: number;
  // Official National Trade / Customs Authority
  natAgency: string;
  natShort: string;
  natDataset: string;
  natBasis: string;
  natNote: string;
  natUrl: string;
  // Commodity mix (5 categories summing to 100%)
  exportMix: TradeCommodityShare[];
  importMix: TradeCommodityShare[];
  // Top 5 bilateral partners
  partners: TradePartnerRecord[];
}

