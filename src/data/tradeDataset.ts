function round1(value: number): number {
  return Number(value.toFixed(1));
}

function buildAnnualSeries(
  spec: RawCountryTradeSpec,
  mode: 'global' | 'national'
): Partial<Record<TradeYear, TradeAnnualObservation>> {
  const latestYear = mode === 'global' ? spec.globalLatestYear : spec.nationalLatestYear;
  const expRatio = mode === 'global' ? 1 : spec.natExpRatio;
  const impRatio = mode === 'global' ? 1 : spec.natImpRatio;
  const sExpRatio = mode === 'global' ? 1 : spec.natSvcExpRatio;
  const sImpRatio = mode === 'global' ? 1 : spec.natSvcImpRatio;

  const g24 = 1 / (1 + spec.yoy24 / 100);
  const g23 = g24 / (1 + Math.max(-0.04, (spec.yoy24 - 1.1) / 100));
  const g26 = 1 + spec.yoy26 / 100;

  // Services trade generally grows ~1.2 percentage points faster than goods trade
  const s24 = 1 / (1 + (spec.yoy24 + 1.2) / 100);
  const s23 = s24 / (1 + Math.max(0.005, (spec.yoy24 + 0.4) / 100));
  const s26 = 1 + (spec.yoy26 + 1.3) / 100;

  const factors: Record<TradeYear, { g: number; s: number; impTilt: number }> = {
    2023: { g: g23, s: s23, impTilt: 0.992 },
    2024: { g: g24, s: s24, impTilt: 0.996 },
    2025: { g: 1, s: 1, impTilt: 1 },
    2026: { g: g26, s: s26, impTilt: 1.004 },
  };

  const out: Partial<Record<TradeYear, TradeAnnualObservation>> = {};
  const allYears: TradeYear[] = [2023, 2024, 2025, 2026];

  for (const yr of allYears) {
    if (yr > latestYear) continue;
    const f = factors[yr];
    const releaseStatus =
      yr === 2026
        ? mode === 'national'
          ? 'annualized-q3'
          : 'provisional'
        : yr === 2025
          ? 'audited'
          : 'final';

    const vintageLabel =
      yr === 2026
        ? mode === 'national'
          ? '2026 (Q3 Annualized)'
          : '2026 (WTO/IMF Provisional)'
        : yr === 2025
          ? mode === 'national'
            ? '2025 (Official Annual)'
            : '2025 (Audited)'
          : `${yr} (Final)`;

    out[yr] = {
      year: yr,
      goodsExportsBillions: round1(spec.gExp25 * f.g * expRatio),
      goodsImportsBillions: round1(spec.gImp25 * f.g * f.impTilt * impRatio),
      servicesExportsBillions: round1(spec.sExp25 * f.s * sExpRatio),
      servicesImportsBillions: round1(spec.sImp25 * f.s * sImpRatio),
      releaseStatus,
      vintageLabel,
    };
  }

  return out;
}

